  async function handleConfirmPosition(step) {
    if (!currentHighlightedElement) {
      showToast("⚠️ 未找到当前高亮元素，请先确保系统已定位到目标。");
      return;
    }

    let selector = "";
    let controlType = "";
    let frameSelector = "";
    let parameters = false;
    let domlocator = "";

    // 如果高亮元素是一个 <iframe>（说明目标在 iframe 里），
    // selector 应该用 iframe worker 之前回传的那个（存哪了？）
    // 我们把它存在 currentHighlightedElement 的临时属性上
    if (currentHighlightedElement.tagName === "IFRAME") {
      selector = currentHighlightedElement.__appguide_review_iframe_selector || "";
      if (!selector) {
        // 如果之前没存（极端情况），退回到用 generateStableSelector 在顶层文档里
        // 给这个 iframe 标签生成一个 selector —— 但这通常不对，因为目标在 iframe 内部
        showToast("请点击 修改定位 人工确认目标控件在页面中的位置是否正确，确认无误后继续。");
        return;
      }
      controlType = currentHighlightedElement.__appguide_review_iframe_controlType || "";
      parameters = currentHighlightedElement.__appguide_review_iframe_parameters === true;
      domlocator = currentHighlightedElement.__appguide_review_iframe_domlocator || "";
      // currentHighlightedElement 此时就是那个 <iframe> 标签本身，直接生成它在顶层文档里的 selector
      frameSelector = generateStableSelector(currentHighlightedElement);
    } else {
      selector = generateStableSelector(currentHighlightedElement);
      controlType = detectControlType(currentHighlightedElement);
      parameters = detectParameters(currentHighlightedElement);
      domlocator = generateStableSelector(resolveInteractiveElement(currentHighlightedElement));
    }

    if (!selector) {
      // 无法生成稳定 selector，仍确认步骤但走语义检索
//       console.log(`[BusinessGuide-Review] ⚠️ 步骤"${step.title}"无法生成稳定selector，将使用语义检索`);
    }

    const isIframeTarget = currentHighlightedElement.tagName === "IFRAME";
    const options = await readStepOptions(controlType,
      isIframeTarget ? null : currentHighlightedElement, isIframeTarget ? currentHighlightedElement : null, selector);
    if (!isStillCurrentStep(step)) return;

    recordStepSelector(step, selector, controlType, frameSelector, parameters, options, domlocator);
    updateUIAfterConfirm(selector, controlType, frameSelector, parameters, options, domlocator);

    // 高亮样式改为确认样式
    if (highlightElement) {
      highlightElement.classList.remove("guide-review-style-pulse", "guide-review-style-solid", "guide-review-style-glow");
      highlightElement.classList.add("guide-review-style-confirmed");
    }

//     console.log(`[BusinessGuide-Review] ✅ 步骤"${step.title}"定位确认，selector: "${selector}"`);
//     console.log("[BusinessGuide-Review] 当前录制结果:", recordingResults);
  }


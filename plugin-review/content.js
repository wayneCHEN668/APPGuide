  function handleStartCorrection(step) {
    if (isPickMode) return;

//     console.log(`[BusinessGuide-Review] 🔍 进入取件模式，步骤: "${step.title}"`);
    isPickMode = true;

    // 禁用气泡上的按钮，防止用户误操作
    if (bubbleElement) {
      const btns = bubbleElement.querySelectorAll("button");
      btns.forEach(b => b.disabled = true);
    }

    // 显示顶部提示条
    pickOverlayHintEl = document.createElement("div");
    pickOverlayHintEl.className = "guide-review-pick-overlay-hint";
    pickOverlayHintEl.textContent = "🎯 请在页面上点击正确的元素（按 Esc 取消）";
    document.body.appendChild(pickOverlayHintEl);

    // 创建悬停高亮层
    pickHoverEl = document.createElement("div");
    pickHoverEl.className = "guide-review-pick-hover";
    pickHoverEl.style.display = "none";
    document.body.appendChild(pickHoverEl);

    // 挂载悬停监听（mousemove）
    document.addEventListener("mousemove", onPickMouseMove, true);
    // 挂载点击拦截（capture 阶段 + preventDefault + stopPropagation）
    document.addEventListener("click", onPickClick, true);
    // 挂载 Esc 取消
    document.addEventListener("keydown", onPickKeyDown, true);

    // 同时广播给所有子 iframe：进入取件模式
    document.querySelectorAll("iframe").forEach((el) => {
      try {
        el.contentWindow && el.contentWindow.postMessage({
          __appguide_review: true,
          type: "start-pick",
          requestId: "pick_" + Date.now(),
        }, "*");
      } catch (e) { /* 忽略 */ }
    });
  }

  function exitPickMode(cancelled) {
    if (!isPickMode) return;
    isPickMode = false;

    document.removeEventListener("mousemove", onPickMouseMove, true);
    document.removeEventListener("click", onPickClick, true);
    document.removeEventListener("keydown", onPickKeyDown, true);

    // 清理 UI
    if (pickHoverEl && pickHoverEl.parentNode) {
      pickHoverEl.parentNode.removeChild(pickHoverEl);
    }
    pickHoverEl = null;

    if (pickOverlayHintEl && pickOverlayHintEl.parentNode) {
      pickOverlayHintEl.parentNode.removeChild(pickOverlayHintEl);
    }
    pickOverlayHintEl = null;

    if (pickConfirmEl && pickConfirmEl.parentNode) {
      pickConfirmEl.parentNode.removeChild(pickConfirmEl);
    }
    pickConfirmEl = null;

    // 恢复气泡按钮
    if (bubbleElement) {
      const btns = bubbleElement.querySelectorAll("button");
      btns.forEach(b => b.disabled = false);
    }

    // 通知所有子 iframe：取消取件模式
    document.querySelectorAll("iframe").forEach((el) => {
      try {
        el.contentWindow && el.contentWindow.postMessage({
          __appguide_review: true,
          type: "cancel-pick",
        }, "*");
      } catch (e) { /* 忽略 */ }
    });

    // resolve pick promise if waiting
    if (pickResolve && cancelled) {
      pickResolve(null);
      pickResolve = null;
    }
  }

  function onPickMouseMove(e) {
    if (!isPickMode || !pickHoverEl) return;
    // 当确认弹窗正在显示时，不显示跟随鼠标的高亮
    if (pickConfirmEl) {
      pickHoverEl.style.display = "none";
      return;
    }
    const target = e.target;
    if (!target || target === document.body || target === document.documentElement) {
      pickHoverEl.style.display = "none";
      return;
    }
    // 排除我们自己的 UI 元素
    if (target.closest && (target.closest(".guide-review-extension-bubble") || target.closest(".guide-review-extension-highlight") ||
        target.closest(".guide-review-pick-hover") || target.closest(".guide-review-pick-confirm") ||
        target.closest(".guide-review-pick-overlay-hint"))) {
      pickHoverEl.style.display = "none";
      return;
    }
    const rect = target.getBoundingClientRect();
    pickHoverEl.style.top = rect.top + "px";
    pickHoverEl.style.left = rect.left + "px";
    pickHoverEl.style.width = rect.width + "px";
    pickHoverEl.style.height = rect.height + "px";
    pickHoverEl.style.display = "block";
  }

  function onPickClick(e) {
//     console.log("[DEBUG] onPickClick FIRED, isPickMode=", isPickMode);
    if (!isPickMode) return;

    const target = e.target;
//     console.log("[DEBUG] target=", target ? target.tagName : "null");
    if (!target || target === document.body || target === document.documentElement) return;

    // 排除我们自己的 UI —— 必须在 preventDefault 之前，否则确认/重新选择按钮不响应
    if (target.closest && (target.closest(".guide-review-extension-bubble") || target.closest(".guide-review-pick-overlay-hint") ||
        target.closest(".guide-review-pick-confirm"))) return;

    e.preventDefault();
    e.stopPropagation();

//     console.log("[BusinessGuide-Review] 🎯 取件模式：用户点击了元素", target);

    // 先用正式高亮样式标出来，弹出二次确认
    // 移除旧的确认框
    if (pickConfirmEl && pickConfirmEl.parentNode) {
      pickConfirmEl.parentNode.removeChild(pickConfirmEl);
    }

    // 临时高亮选中元素
    if (highlightElement) {
      highlightElement.classList.remove("guide-review-style-pulse", "guide-review-style-solid", "guide-review-style-glow", "guide-review-style-confirmed");
      // 不直接改 highlightElement，而是创建一个临时预览高亮
    }

    const rect = target.getBoundingClientRect();
    pickConfirmEl = document.createElement("div");
    pickConfirmEl.className = "guide-review-pick-confirm";
    pickConfirmEl.style.position = "fixed";
    // 根据下方空间是否足够决定放到元素下方还是上方
    const estimatedHeight = 40;
    const spaceBelow = window.innerHeight - rect.bottom - 8;
    if (spaceBelow >= estimatedHeight) {
      pickConfirmEl.style.top = Math.max(rect.bottom + 8, 10) + "px";
    } else {
      pickConfirmEl.style.top = Math.max(rect.top - estimatedHeight - 8, 10) + "px";
    }
    pickConfirmEl.style.left = Math.max(rect.left, 10) + "px";
    pickConfirmEl.innerHTML = `
      <span>是这个元素吗？</span>
      <button class="guide-review-pick-yes">✓ 确认</button>
      <button class="guide-review-pick-no">重新选择</button>
    `;
    document.body.appendChild(pickConfirmEl);
//     console.log("[DEBUG] pickConfirmEl appended, rect:", rect, "style:", pickConfirmEl.style.cssText);

    // 隐藏跟随鼠标的高亮，等用户点击"重新选择"后再恢复
    if (pickHoverEl) {
      pickHoverEl.style.display = "none";
    }

    // 被点击元素保持绿色确认高亮，醒目提醒用户选中了什么
    if (highlightElement) {
      updateHighlightPosition(target);
      highlightElement.classList.add("guide-review-style-confirmed");
    }

    pickConfirmEl.querySelector(".guide-review-pick-yes").onclick = async (ev) => {
      ev.stopPropagation();
      // 用户确认选中
      const selector = generateStableSelector(target);
      const controlType = detectControlType(target);
      const parameters = detectParameters(target);
      const domlocator = generateStableSelector(resolveInteractiveElement(target));
      // 理论上这里的 target 不会是 <iframe>（iframe 内部点击走的是 _iframePickClick + 消息中转），
      // 防御性地按同样逻辑处理，与 handleConfirmPosition 保持一致
      const frameSelector = target.tagName === "IFRAME" ? generateStableSelector(target) : "";
//       console.log(`[BusinessGuide-Review] ✅ 用户手动确认元素，selector: "${selector || '(无法生成稳定selector，将使用语义检索)'}"`);

      exitPickMode();

      // 用新元素重新绘制高亮
      if (highlightElement && highlightElement.parentNode) {
        highlightElement.parentNode.removeChild(highlightElement);
      }
      currentHighlightedElement = target;
      createHighlightForElement(target, "confirmed");

      // 记录 selector（如果生成了稳定 selector；否则只确认步骤，后续走语义匹配）
      const step = activeGuide && activeGuide.steps[currentStepIndex];
      if (step) {
        const options = await readStepOptions(controlType, target, null, selector);
        if (!isStillCurrentStep(step)) return;
        recordStepSelector(step, selector, controlType, frameSelector, parameters, options, domlocator);

        // 如果是从"未找到元素"触发的人工确认，渲染当前步骤气泡让用户手动点"下一步"
        if (pickFromNotFound) {
          pickFromNotFound = false;
//           console.log(`[BusinessGuide-Review] ✅ 人工确认完成，渲染当前步骤气泡。`);
          showToast("✅ 人工确认完成，请点击下一步继续。");
          renderBubble(step, target);
          return;
        }

        // 原地更新现有气泡（正常的"修改定位"流程）
        updateUIAfterConfirm(selector, controlType, frameSelector, parameters, options, domlocator);
        // 气泡重新定位到新选中的元素旁边
        positionBubble(target, step.tipPosition);
      }
    };

    pickConfirmEl.querySelector(".guide-review-pick-no").onclick = (ev) => {
      ev.stopPropagation();
      // 清除被点击元素上的临时绿色高亮
      if (highlightElement) {
        highlightElement.classList.remove("guide-review-style-confirmed");
        highlightElement.style.display = "none";
      }
      // 移除确认框，用户可以继续选择
      if (pickConfirmEl && pickConfirmEl.parentNode) {
        pickConfirmEl.parentNode.removeChild(pickConfirmEl);
      }
      pickConfirmEl = null;
    };
  }

  function onPickKeyDown(e) {
    if (e.key === "Escape") {
//       console.log("[BusinessGuide-Review] 取件模式：用户按 Esc 取消");
      if (pickFromNotFound) {
        // 从"未找到元素"触发的人工确认 → 回到三按钮确认对话框
        pickFromNotFound = false;
        exitPickMode(true);
        const step = activeGuide && activeGuide.steps[currentStepIndex];
        if (step) {
          showConfirmDialog(step,
            () => { saveCurrentEdits(); advanceStep(); },
            () => { showToast("引导已中止，审核进度已清除。"); disableGuide(); },
            () => {
              pickFromNotFound = true;
              handleStartCorrection(step);
            },
            () => { deleteCurrentStep(true); }
          );
        }
      } else {
        exitPickMode(true);
      }
    }
  }


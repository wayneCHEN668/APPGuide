  function updateHighlightPosition(element) {
    if (!highlightElement) return;
    const rect = element.getBoundingClientRect();
    highlightElement.style.top = `${rect.top + window.scrollY - 4}px`;
    highlightElement.style.left = `${rect.left + window.scrollX - 4}px`;
    highlightElement.style.width = `${rect.width + 8}px`;
    highlightElement.style.height = `${rect.height + 8}px`;
  }

  function positionBubble(target, position) {
    if (!bubbleElement) return;
    const gap = 12;
    if (!target) {
      bubbleElement.style.top = "30%";
      bubbleElement.style.left = "50%";
      bubbleElement.style.transform = "translate(-50%, -30%)";
      bubbleElement.style.position = "fixed";
      return;
    }
    target.scrollIntoView({ block: "center", inline: "nearest" });
    const tRect = target.getBoundingClientRect();
    const bRect = bubbleElement.getBoundingClientRect();
    const scrollY = window.scrollY;
    const scrollX = window.scrollX;
    const viewportWidth = window.innerWidth;

    let effectivePosition = (position === "top" || position === "bottom" || position === "left") ? position : "right";
    const spaceOnRight = viewportWidth - (tRect.right + gap);
    const spaceOnLeft = tRect.left - gap;

    if (effectivePosition === "right" && spaceOnRight < bRect.width) {
      if (spaceOnLeft >= bRect.width || spaceOnLeft > spaceOnRight) effectivePosition = "left";
    } else if (effectivePosition === "left" && spaceOnLeft < bRect.width) {
      if (spaceOnRight >= bRect.width || spaceOnRight > spaceOnLeft) effectivePosition = "right";
    }

    let top = 0, left = 0;
    switch (effectivePosition) {
      case "top":
        top = tRect.top + scrollY - bRect.height - gap;
        left = tRect.left + scrollX + tRect.width / 2 - bRect.width / 2;
        break;
      case "bottom":
        top = tRect.bottom + scrollY + gap;
        left = tRect.left + scrollX + tRect.width / 2 - bRect.width / 2;
        break;
      case "left":
        top = tRect.top + scrollY + tRect.height / 2 - bRect.height / 2;
        left = tRect.left + scrollX - bRect.width - gap;
        break;
      case "right":
      default:
        top = tRect.top + scrollY + tRect.height / 2 - bRect.height / 2;
        left = tRect.right + scrollX + gap;
    }

    left = Math.max(10, Math.min(left, window.innerWidth - bRect.width - 20));
    top = Math.max(10, Math.min(top, document.documentElement.scrollHeight - bRect.height - 20));

    bubbleElement.style.top = `${top}px`;
    bubbleElement.style.left = `${left}px`;
  }

  /** 保存当前输入框的 title/description 修改到 step 和 _fullFlowData */
  function saveCurrentEdits() {
    if (!activeGuide || !activeGuide.steps || !activeGuide.steps[currentStepIndex]) return;

    const titleInput = document.getElementById("guide-review-input-title");
    const descTextarea = document.getElementById("guide-review-textarea-desc");

    if (titleInput) {
      activeGuide.steps[currentStepIndex].title = titleInput.value.trim() || activeGuide.steps[currentStepIndex].title;
    }
    if (descTextarea) {
      activeGuide.steps[currentStepIndex].description = descTextarea.value.trim() || activeGuide.steps[currentStepIndex].description;
    }

    // 同步到完整流程数据（如果有的话）
    if (_fullFlowData && flowMeta && _fullFlowData.pages && _fullFlowData.pages[flowMeta.pageIndex]) {
      const pageSteps = _fullFlowData.pages[flowMeta.pageIndex].steps;
      if (pageSteps && pageSteps[currentStepIndex]) {
        pageSteps[currentStepIndex].title = activeGuide.steps[currentStepIndex].title;
        pageSteps[currentStepIndex].description = activeGuide.steps[currentStepIndex].description;
      }
      // 将修改后的完整数据持久化到存储
      persistFlowData(_fullFlowData, flowMeta.pageIndex);
    }
  }

  /** 删除当前步骤（skipConfirm 为 true 时跳过确认弹窗，用于「未找到控件」对话框的「删除步骤」按钮） */
  function deleteCurrentStep(skipConfirm = false) {
    if (!activeGuide || !activeGuide.steps || activeGuide.steps.length === 0 || !flowMeta) return;
    // 完整流程数据是新流程启动后异步拉取的，未就绪时删除会丢失或误删
    if (!_fullFlowData || !_fullFlowData.pages || !_fullFlowData.pages[flowMeta.pageIndex]) {
      showToast("流程数据加载中，请稍后再删除。");
      return;
    }

    const deletedIndex = currentStepIndex;
    const wasLast = deletedIndex === activeGuide.steps.length - 1;
    const isLastPageOfFlow = flowMeta.pageIndex >= flowMeta.totalPages - 1;
    const globalNum = activeGuide.steps[deletedIndex].globalStepNumber || (deletedIndex + 1);
    const confirmText = (wasLast && isLastPageOfFlow)
      ? "确定要删除步骤 " + globalNum + " 吗？这是最后一步，删除后将完成审核并提交。"
      : "确定要删除步骤 " + globalNum + " 吗？此操作不可撤销。";
    if (!skipConfirm && !confirm(confirmText)) return;

    // 从当前活动步骤数组和完整流程数据中移除
    activeGuide.steps.splice(deletedIndex, 1);
    const pageSteps = _fullFlowData.pages[flowMeta.pageIndex].steps;
    if (pageSteps) pageSteps.splice(deletedIndex, 1);
    persistFlowData(_fullFlowData, flowMeta.pageIndex);

    // 确认缓存按 pageIndex:index 记录，删除后本页后续步骤的键整体前移一位
    currentStepConfirmed = false;
    const shifted = {};
    for (const key of Object.keys(reviewConfirmedCache)) {
      const [p, i] = key.split(":").map(Number);
      if (p !== flowMeta.pageIndex || i < deletedIndex) shifted[key] = reviewConfirmedCache[key];
      else if (i > deletedIndex) shifted[`${p}:${i - 1}`] = reviewConfirmedCache[key];
    }
    reviewConfirmedCache = shifted;

    recalcGlobalStepNumbers();
    trackFlowStat(flowMeta.flowId, "step");

    // 删除的是本页最后一步（含本页已删空）→ 视为本页审核完成
    if (wasLast) {
      finishCurrentPage();
      return;
    }

    // currentStepIndex 不变，已指向原来的下一步
    renderGuideUI();
    if (!isGuideActive || !activeGuide) return;
    persistFlowState(activeGuide.steps[currentStepIndex].globalStepNumber);
  }

  /** 根据完整流程数据重新计算当前页步骤的 globalStepNumber 及 flowMeta 的偏移量和总步骤数 */
  function recalcGlobalStepNumbers() {
    if (!_fullFlowData || !_fullFlowData.pages || !flowMeta) return;
    let globalStepOffset = 0;
    let totalSteps = 0;
    for (let i = 0; i < _fullFlowData.pages.length; i++) {
      const count = (_fullFlowData.pages[i].steps || []).length;
      if (i < flowMeta.pageIndex) globalStepOffset += count;
      totalSteps += count;
    }
    flowMeta.globalStepOffset = globalStepOffset;
    flowMeta.totalSteps = totalSteps;
    if (activeGuide && activeGuide.steps) {
      activeGuide.steps.forEach((step, j) => { step.globalStepNumber = globalStepOffset + j + 1; });
    }
  }

  function prevStep() {
    if (currentStepIndex > 0) {
      currentStepIndex--;
      currentStepConfirmed = false;
      if (flowMeta) trackFlowStat(flowMeta.flowId, "step");
      renderGuideUI();
      if (!isGuideActive || !activeGuide) return;
      persistFlowState(activeGuide.steps[currentStepIndex].globalStepNumber);
    }
  }

  function advanceStep() {
    if (!isGuideActive || !activeGuide || !Array.isArray(activeGuide.steps)) return;

    const isLastStepOnPage = currentStepIndex >= activeGuide.steps.length - 1;

    if (!isLastStepOnPage) {
      currentStepIndex++;
      currentStepConfirmed = false;
      if (flowMeta) trackFlowStat(flowMeta.flowId, "step");
      renderGuideUI();
      if (!isGuideActive || !activeGuide) return;
      persistFlowState(activeGuide.steps[currentStepIndex].globalStepNumber);
      return;
    }

    finishCurrentPage();
  }

  /** 本页审核结束：最后一页则提交整个流程，否则保存进度并等待用户前往下一页 */
  function finishCurrentPage() {
    const isLastPageOfFlow = !flowMeta || flowMeta.pageIndex >= flowMeta.totalPages - 1;

    if (isLastPageOfFlow) {
      // 【阶段五】整个跨页流程全部完成 → 提交完整 steps JSON
      submitFullFlow();
    } else {
      // 本页不是最后一页 → 持久化完整数据，递增 pageIndex
      if (_fullFlowData) {
        persistFlowData(_fullFlowData, flowMeta.pageIndex);
      }
      // 用 offset + 本页步数计算下一页首步编号（本页步骤被删空时同样成立）
      const nextGlobalNum = flowMeta.globalStepOffset + activeGuide.steps.length + 1;
      const nextPageIndex = flowMeta.pageIndex + 1;
      persistFlowState(nextGlobalNum, nextPageIndex);
      showToast("✅ 本页审核已完成，请前往下一步骤对应页面，按 Alt+C 继续审核。");
      isGuideActive = false;
      activeGuide = null;
      flowMeta = null;
      cleanupUI();
    }
  }


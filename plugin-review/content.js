  function tokenize(text) {
    if (!text) return [];
    const clean = text.toLowerCase().trim();
    const tokens = [];
    for (let i = 0; i < clean.length; i++) {
      tokens.push(clean[i]);
    }
    for (let i = 0; i < clean.length - 1; i++) {
      tokens.push(clean.substring(i, i + 2));
    }
    const words = clean.split(/[^a-z0-9一-鿿]+/i).filter(w => w.length > 1);
    tokens.push(...words);
    return tokens;
  }

  function computeSimilarity(textA, textB) {
    const tokensA = tokenize(textA);
    const tokensB = tokenize(textB);
    if (tokensA.length === 0 || tokensB.length === 0) return 0;
    const countsA = {};
    const countsB = {};
    tokensA.forEach(t => countsA[t] = (countsA[t] || 0) + 1);
    tokensB.forEach(t => countsB[t] = (countsB[t] || 0) + 1);
    const allTokens = new Set([...Object.keys(countsA), ...Object.keys(countsB)]);
    let dotProduct = 0;
    let normA = 0;
    let normB = 0;
    allTokens.forEach(t => {
      const valA = countsA[t] || 0;
      const valB = countsB[t] || 0;
      dotProduct += valA * valB;
      normA += valA * valA;
      normB += valB * valB;
    });
    if (normA === 0 || normB === 0) return 0;
    return dotProduct / (Math.sqrt(normA) * Math.sqrt(normB));
  }

  function looksLikeLabelText(el) {
    if (!el || !el.tagName) return false;
    const tag = el.tagName.toLowerCase();
    if (tag === "input" || tag === "select" || tag === "textarea" || tag === "button" ||
        tag === "a" || tag === "svg" || tag === "img") {
      return false;
    }
    const text = (el.textContent || "").trim();
    if (!text || text.length > 20) return false;
    if (el.querySelector && el.querySelector("input, select, textarea, button, a, [role='button'], [tabindex]")) {
      return false;
    }
    return true;
  }

  function scanDOM() {
    const list = [];
    const seen = new Set();

    function pushCandidate(el) {
      if (seen.has(el)) return;
      seen.add(el);

      try {
        const cs = getComputedStyle(el);
        const tag = el.tagName.toLowerCase();
        const isHiddenByStyle = cs.display === "none" || cs.visibility === "hidden" || parseFloat(cs.opacity) === 0;
        if (isHiddenByStyle) return;
        const rect = el.getBoundingClientRect();
        if (rect.width === 0 && rect.height === 0) {
          if (tag !== "input") return;
          const parent = el.parentElement;
          if (parent) {
            const pr = parent.getBoundingClientRect();
            if (pr.width === 0 && pr.height === 0) return;
          }
        }

        // 排除"被折叠容器裁掉"的元素：手风琴/折叠菜单收起时，
        // 容器 height:0 + overflow:hidden，子项自身仍有完整布局尺寸，
        // 上面那几道检查拦不住，需沿祖先链检测。
        let clipAncestor = el.parentElement;
        for (let lv = 0; lv < 8 && clipAncestor && clipAncestor !== document.body; lv++) {
          const ar = clipAncestor.getBoundingClientRect();
          if (ar.height === 0 || ar.width === 0) {
            const acs = getComputedStyle(clipAncestor);
            if (acs.overflow !== "visible" || acs.overflowX !== "visible" || acs.overflowY !== "visible") {
              return;
            }
          }
          clipAncestor = clipAncestor.parentElement;
        }
      } catch (e) { /* 忽略 */ }

      const id = el.id || "";
      const tagName = el.tagName.toLowerCase();
      const placeholder = el.placeholder || "";
      const className = (typeof el.className === "string") ? el.className : "";
      const ariaLabel = el.getAttribute("aria-label") || "";
      const textContent = el.textContent ? el.textContent.trim() : "";

      let labelText = "";
      let labelFromSelf = false;
      if (id) {
        const labelEl = document.querySelector(`label[for="${CSS.escape(id)}"]`);
        if (labelEl) {
          labelText = labelEl.textContent || "";
          labelFromSelf = true;
        }
      }

      if (!labelText) {
        if ((tagName === "button" || tagName === "a" || el.getAttribute("role") === "button") && textContent) {
          labelText = textContent;
          labelFromSelf = true;
        }
      }

      if (!labelText) {
        let ownText = "";
        for (let ci = 0; ci < el.childNodes.length; ci++) {
          const child = el.childNodes[ci];
          if (child.nodeType === Node.TEXT_NODE && child.textContent.trim()) {
            ownText += child.textContent.trim();
          }
        }
        if (ownText && ownText.length < 30) {
          labelText = ownText;
          labelFromSelf = true;
        }
      }

      if (!labelText) {
        let scanEl = el;
        for (let level = 0; level < 6 && !labelText && scanEl; level++) {
          let prev = scanEl.previousElementSibling;
          while (prev) {
            if (looksLikeLabelText(prev)) {
              labelText = (prev.textContent || "").trim();
              break;
            }
            prev = prev.previousElementSibling;
          }
          scanEl = scanEl.parentElement;
        }
      }

      if (!labelText) {
        if (tagName === "button" || tagName === "a" || el.getAttribute("role") === "button") {
          labelText = textContent;
          labelFromSelf = !!textContent;
        } else if ((tagName === "div" || tagName === "span" || tagName === "p" || /^h[3-6]$/.test(tagName)) && textContent && textContent.length < 30) {
          labelText = textContent;
          labelFromSelf = true;
        } else {
          const parent = el.parentElement;
          if (parent) labelText = parent.textContent ? parent.textContent.trim() : "";
        }
      }

      labelText = labelText.replace(/\s+/g, " ").substring(0, 100);

      if (ariaLabel && !textContent) {
        labelText = ariaLabel;
        labelFromSelf = true;
      } else if (!labelText && ariaLabel) {
        labelText = ariaLabel;
        labelFromSelf = true;
      } else if (labelText && ariaLabel && !labelText.includes(ariaLabel)) {
        labelText = ariaLabel + " " + labelText;
        labelFromSelf = true;
      }

      let selector = "";
      if (id) {
        selector = `#${id}`;
      } else if (className) {
        const firstClass = className.split(/\s+/)[0];
        if (firstClass && !firstClass.includes(":") && !firstClass.includes("[")) {
          selector = `${tagName}.${firstClass}`;
        } else {
          selector = tagName;
        }
      } else {
        selector = tagName;
      }

      if (selector && !className.includes("guide-review-extension")) {
        // 过滤空壳图标元素：自身无直接文本节点，仅包含svg/img等图标子节点，
        // 且label是从旁边"借"来的（sibling walk / 父容器文本）。
        // 但"自带标签"的元素不在此列（labelFromSelf）：纯图标按钮的 aria-label
        // 就写在它自己身上，是它唯一也是正确的语义标签。
        if (labelText && !labelFromSelf) {
          var hasOwnDirectText = false;
          for (var ci = 0; ci < el.childNodes.length; ci++) {
            var child = el.childNodes[ci];
            if (child.nodeType === Node.TEXT_NODE && child.textContent.trim()) {
              hasOwnDirectText = true;
              break;
            }
          }
          if (!hasOwnDirectText && el.querySelector && el.querySelector("svg, img, i[class*='icon'], span[class*='icon']")) {
            return; // 空图标壳子，不纳入候选池
          }
        }

        list.push({
          element: el,
          selector: selector,
          label: labelText || placeholder || id || tagName,
          placeholder: placeholder,
          className: className,
          ariaLabel: ariaLabel,
          type: tagName
        });
      }
    }

    document.querySelectorAll(
      "input, select, textarea, button, a, [role='button'], div[class*='submit'], div[class*='btn'], div[class*='Btn'], [class*='submit-btn'], div[class*='switch'], div[class*='icon-button'], [class*='cursor-pointer']"
    ).forEach(pushCandidate);

    const INTERACTIVE_ROLES = ["button", "combobox", "listbox", "menuitem", "tab", "checkbox", "radio", "switch", "option"];
    document.querySelectorAll("[tabindex], [role]").forEach(el => {
      if (seen.has(el)) return;
      const role = el.getAttribute("role");
      if (el.hasAttribute("tabindex") || (role && INTERACTIVE_ROLES.includes(role))) {
        pushCandidate(el);
      }
    });

    document.querySelectorAll("div, span, p").forEach(el => {
      if (seen.has(el)) return;
      if (el.querySelector("input, select, textarea, button, a[href]")) return;
      const text = (el.textContent || "").trim();
      if (!text || text.length > 30) return;
      if (!el.querySelector("svg, img")) return;
      if (el.querySelectorAll("*").length > 15) return;
      pushCandidate(el);
    });

    document.querySelectorAll("div, span, p, h3, h4, h5, h6").forEach(el => {
      if (seen.has(el)) return;
      if (el.querySelector("input, select, textarea, button, a[href]")) return;
      const text = (el.textContent || "").trim();
      if (text.length > 30) return;
      if (el.querySelectorAll("*").length > 10) return;
      try {
        if (getComputedStyle(el).cursor === "pointer") {
          pushCandidate(el);
        }
      } catch (e) { /* 忽略 */ }
    });

    return list;
  }

  function pickPreferUnused(items) {
    const mostSpecific = items.filter((it) =>
      !items.some((other) => other !== it && it.element.contains(other.element))
    );
    const pool = mostSpecific.length > 0 ? mostSpecific : items;
    const unused = pool.find((it) => !usedElements.has(it.element));
    return unused || pool[0];
  }

  // S0 策略：完整标题精确匹配。提取为独立函数，供主页和 iframe worker 复用。
  function findS0Match(step, scanned) {
    if (!scanned) scanned = scanDOM();
    if (scanned.length === 0) return null;

    const rawText = (step.clickText || step.title) || "";
    if (!rawText) return null;
    const spaceIdx = rawText.indexOf(" ");
    const matchText = spaceIdx > 0 ? rawText.substring(0, spaceIdx) : rawText;
    const stripSymbols = (str) => str.replace(/[^\w一-鿿\s]/g, '').replace(/(?:一个|一下|一份|一次)/g, '').replace(/\s+/g, ' ').trim();
    const normalizedTitle = stripSymbols(matchText);

    if (normalizedTitle.length === 0) return null;

    const s0Matches = [];
    for (const item of scanned) {
      const normalizedLabel = stripSymbols(item.label);
      if (normalizedLabel === normalizedTitle) {
        s0Matches.push(item);
      }
    }
    if (s0Matches.length > 0) {
      const chosen = pickPreferUnused(s0Matches);
      return { element: chosen.element, selector: chosen.selector, label: chosen.label, score: 0.95 };
    }
    return null;
  }

  function findBestSemanticMatch(step) {
    const scanned = scanDOM();
    if (scanned.length === 0) return null;

    const isDebug = !!window.__appguideReviewDebug;
    if (isDebug) {
//       console.log("[DEBUG] === 匹配步骤:", step.title, "===", IS_TOP_FRAME ? "(顶层文档)" : "(iframe worker)");
//       console.log("[DEBUG] 扫描到", scanned.length, "个控件");
    }

        // Strategy 0: exact title match, delegated to findS0Match for cross-frame reuse
    if (isDebug) {
//      const _s0dbg = (str) => str.replace(/[^\w\u4e00-\u9fff\s]/g, '').replace(/(?:\u4e00\u4e2a|\u4e00\u4e0b|\u4e00\u4efd|\u4e00\u6b21)/g, '').replace(/\s+/g, ' ').trim();
//      const _rawText = step.clickText || step.title;
//      const _spaceIdx = _rawText.indexOf(" ");
//      const _matchText = _spaceIdx > 0 ? _rawText.substring(0, _spaceIdx) : _rawText;
//       console.log("[DEBUG] S0 完整标题匹配: matchText =", JSON.stringify(_matchText), "(来源:", step.clickText ? "clickText" : "title", ")", "normalized =", JSON.stringify(_s0dbg(_matchText)));
    }
    const s0Result = findS0Match(step, scanned);
    if (s0Result) {
//       if (isDebug) console.log("[DEBUG] S0 命中! label:", s0Result.label.substring(0, 30), "(已去重复用)");
      return { ...s0Result, strategy: "s0" };
    }
//     if (isDebug) console.log("[DEBUG] S0 未命中，进入S1");

    const rawText = step.clickText || step.title;
    const spaceIdx = rawText.indexOf(" ");
    const matchText = spaceIdx > 0 ? rawText.substring(0, spaceIdx) : rawText;

    const titleChars = matchText.replace(/^(设置|选择|找到|点击|上传|提交|填写|添加|输入|创建)/, '').trim();
    const s1Matches = [];
    for (const item of scanned) {
      if (titleChars.length >= 2 && item.label.includes(titleChars)) s1Matches.push(item);
    }
    if (s1Matches.length > 0) {
      const chosen = pickPreferUnused(s1Matches);
      return { element: chosen.element, selector: chosen.selector, label: chosen.label, score: 0.90, strategy: "s1" };
    }

    let s2Matches = [];
    for (const item of scanned) {
      const labelLen = item.label.replace(/\s/g, '').length;
      if (labelLen > 8) continue;
      const titleSet = new Set(matchText.replace(/\s/g, '').split(''));
      const labelSet = new Set(item.label.replace(/\s/g, '').split(''));
      const overlap = [...titleSet].filter(c => labelSet.has(c)).length;
      const titleOverlap = overlap / titleSet.size;
      const labelOverlap = labelSet.size > 0 ? overlap / labelSet.size : 0;
      const bestOverlap = Math.max(titleOverlap, labelOverlap);
      if (bestOverlap >= 0.5 && titleSet.size >= 2 && overlap >= 2) {
        s2Matches.push({ ...item, bestOverlap });
      }
    }
    if (s2Matches.length > 0) {
      const chosen = pickPreferUnused(s2Matches);
      return { element: chosen.element, selector: chosen.selector, label: chosen.label, score: 0.70 + chosen.bestOverlap * 0.30, strategy: "s2" };
    }

    const query = matchText + " " + matchText + " " + matchText + " " + step.description;
    let highestScore = 0;
    let secondBestScore = 0;
    let bestCandidates = [];

    scanned.forEach(item => {
      const score = computeSimilarity(
        query,
        item.label + " " + item.label + " " + item.placeholder + " " + item.ariaLabel
      );
      if (score > highestScore) {
        secondBestScore = highestScore;
        highestScore = score;
        bestCandidates = [item];
      } else if (score === highestScore && score > 0) {
        bestCandidates.push(item);
      } else if (score > secondBestScore) {
        secondBestScore = score;
      }
    });

    let bestMatch = null;
    if (bestCandidates.length > 0) {
      const chosen = pickPreferUnused(bestCandidates);
      bestMatch = { element: chosen.element, selector: chosen.selector, label: chosen.label, score: highestScore, strategy: "s3" };
    }

    const S3_MARGIN = 0.08;
    const hasMargin = secondBestScore === 0 || (highestScore - secondBestScore) >= S3_MARGIN;
    if (bestMatch && bestMatch.score >= 0.50) {
      if (!hasMargin) return null;
      return bestMatch;
    }
    return null;
  }


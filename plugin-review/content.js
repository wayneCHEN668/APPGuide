  function submitFullFlow() {
    if (!_fullFlowData || !flowMeta) {
      showToast("🎉 流程审核完成！");
      clearFlowState();
      disableGuide();
      return;
    }

    // 构造 steps JSON: { title, startUrl, pages: [...] }
    var stepsObj = {
      title: _fullFlowData.title || "",
      startUrl: _fullFlowData.starturl || "",
      pages: _fullFlowData.pages || [],
    };
    var stepsJson = JSON.stringify(stepsObj);

//     console.log("[BusinessGuide-Review] 📤 提交完整 steps JSON:", { flowId: flowMeta.flowId, stepsLength: stepsJson.length });

    showToast("📤 正在提交审核结果...");

    chrome.runtime.sendMessage(
      { action: "submit-full-flow", flowId: flowMeta.flowId, steps: stepsJson },
      function (response) {
        if (chrome.runtime.lastError) {
          console.error("[BusinessGuide-Review] 提交失败:", chrome.runtime.lastError.message);
          showToast("❌ 提交失败，数据已保存在控制台。");
//           console.log("[BusinessGuide-Review] 未成功提交的完整 JSON:", stepsJson);
          return;
        }

        if (response && response.success) {
//           console.log("[BusinessGuide-Review] ✅ 完整 steps JSON 已成功提交");
          showToast("🎉 恭喜！审核完成，流程步骤已成功更新。");
        } else {
          console.error("[BusinessGuide-Review] 服务端返回错误:", response);
          showToast("❌ 服务端处理失败，数据已保存在控制台。");
//           console.log("[BusinessGuide-Review] 未成功提交的完整 JSON:", stepsJson);
        }

        recordingResults = [];
        clearFlowState();
        disableGuide();
      }
    );
  }


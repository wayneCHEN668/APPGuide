  function resolveWithS1S3Local(step, myToken, retriesLeft) {
    if (myToken !== renderRequestToken) return;
    const local = resolveLocalTarget(step);
    if (local) {
      const LOW_CONFIDENCE = 80;
      const _iframeEls = IS_TOP_FRAME ? Array.from(document.querySelectorAll("iframe")) : [];
      if (local.scorePercent < LOW_CONFIDENCE && _iframeEls.length > 0) {
//         console.log("[BusinessGuide-Review] 本地匹配到\"" + step.title + "\"，置信度仅" + local.scorePercent + "%，并行探测iframe以比较...");
        probeChildFrames(step, _iframeEls).then((bestIframe) => {
          if (myToken !== renderRequestToken) return;
          if (!isGuideActive || !activeGuide || activeGuide.steps[currentStepIndex] !== step) return;
          if (bestIframe && bestIframe.score > local.scorePercent) {
//             console.log("[BusinessGuide-Review] iframe匹配(" + bestIframe.score + "%)优于本地(" + local.scorePercent + "%)，采用iframe结果");
            currentHighlightedElement = bestIframe.iframeEl;
            if (bestIframe.selector) {
              currentHighlightedElement.__appguide_review_iframe_selector = bestIframe.selector;
            }
            if (bestIframe.controlType) {
              currentHighlightedElement.__appguide_review_iframe_controlType = bestIframe.controlType;
            }
            currentHighlightedElement.__appguide_review_iframe_parameters = bestIframe.parameters;
            currentHighlightedElement.__appguide_review_iframe_domlocator = bestIframe.domlocator || "";
            renderBubble(step, bestIframe.iframeEl);
          } else {
//             console.log("[BusinessGuide-Review] 本地匹配(" + local.scorePercent + "%)优于或等于iframe，采用本地结果");
            usedElements.add(local.element);
            currentHighlightedElement = local.element;
            createHighlightForElement(local.element, step.highlightStyle);
            renderBubble(step, local.element);
          }
        });
        return;
      }
      usedElements.add(local.element);
      currentHighlightedElement = local.element;
      createHighlightForElement(local.element, step.highlightStyle);
      renderBubble(step, local.element);
      return;
    }

    if (retriesLeft > 0) {
//       console.log("[BusinessGuide-Review] 本文档内暂未找到\"" + step.title + "\"，" + LOCAL_RETRY_DELAY_MS + "ms后重试（剩余" + retriesLeft + "次）...");
      waitForDomSettleOrTimeout(LOCAL_RETRY_DELAY_MS).then(() => {
        resolveWithS1S3Local(step, myToken, retriesLeft - 1);
      });
      return;
    }

    const __iframeEls = IS_TOP_FRAME ? Array.from(document.querySelectorAll("iframe")) : [];
    if (__iframeEls.length === 0) {
      handleTargetNotFound(step);
      return;
    }

    probeChildFrames(step, __iframeEls).then((bestIframe) => {
      if (myToken !== renderRequestToken) return;
      if (!isGuideActive || !activeGuide || activeGuide.steps[currentStepIndex] !== step) return;
      if (bestIframe) {
        currentHighlightedElement = bestIframe.iframeEl;
        if (bestIframe.selector) {
          currentHighlightedElement.__appguide_review_iframe_selector = bestIframe.selector;
        }
        if (bestIframe.controlType) {
          currentHighlightedElement.__appguide_review_iframe_controlType = bestIframe.controlType;
        }
        currentHighlightedElement.__appguide_review_iframe_parameters = bestIframe.parameters;
        currentHighlightedElement.__appguide_review_iframe_domlocator = bestIframe.domlocator || "";
        renderBubble(step, bestIframe.iframeEl);
      } else {
        handleTargetNotFound(step);
      }
    });
  }


  function waitForDomSettleOrTimeout(ms) {
    return new Promise((resolve) => {
      let done = false;
      let observer = null;
      try {
        observer = new MutationObserver(() => {
          if (done) return;
          done = true;
          if (observer) observer.disconnect();
          resolve();
        });
        observer.observe(document.body, { childList: true, subtree: true, attributes: true });
      } catch (e) { /* 退化 */ }
      setTimeout(() => {
        if (done) return;
        done = true;
        if (observer) observer.disconnect();
        resolve();
      }, ms);
    });
  }

  function attemptResolveStep(step, myToken, retriesLeft) {
    if (myToken !== renderRequestToken) return;

//     console.log("[BusinessGuide-Review] attemptResolveStep 进入:", {
//       title: step.title,
//       selector: step.selector,
//       retriesLeft,
//       isTopFrame: IS_TOP_FRAME,
//       iframeCount: IS_TOP_FRAME ? document.querySelectorAll("iframe").length : 0,
//     });

    // ---- Phase 1: Best-match cross-frame (selector → S0) ----
    const _iframeEls_phase1 = IS_TOP_FRAME ? Array.from(document.querySelectorAll("iframe")) : [];

    // === Phase 1a: Selector exact match cross-frame ===
    if (step.selector && step.selector !== "auto") {
      const directHit = document.querySelector(step.selector);

      // selector hits main page, no iframes
      if (directHit && _iframeEls_phase1.length === 0) {
//         console.log("[BusinessGuide-Review] selector匹配\"" + step.selector + "\"于主页面，无iframe，直接采用");
        usedElements.add(directHit);
        currentHighlightedElement = directHit;
        createHighlightForElement(directHit, step.highlightStyle);
        renderBubble(step, directHit);
        return;
      }

      // selector hits main page, with iframes: render now, probe iframes in background
      if (directHit && _iframeEls_phase1.length > 0) {
//         console.log("[BusinessGuide-Review] selector匹配\"" + step.selector + "\"于主页面，并行探测iframe的selector匹配...");
        usedElements.add(directHit);
        currentHighlightedElement = directHit;
        createHighlightForElement(directHit, step.highlightStyle);
        renderBubble(step, directHit);
        probeChildFrames(step, _iframeEls_phase1).then((bestIframe) => {
          if (myToken !== renderRequestToken) return;
          if (!isGuideActive || !activeGuide || activeGuide.steps[currentStepIndex] !== step) return;
          if (bestIframe) {
//             console.log("[BusinessGuide-Review] selector探测: iframe中也找到selector\"" + step.selector + "\"，主页面结果已使用（同分优先主页）");
          } else {
//             console.log("[BusinessGuide-Review] selector探测: iframe无selector匹配，主页面结果唯一");
          }
        });
        return;
      }

      // selector misses main page, has iframes: probe iframes for selector
      if (!directHit && _iframeEls_phase1.length > 0) {
//         console.log("[BusinessGuide-Review] selector未命中主页\"" + step.selector + "\"，探测iframe的selector匹配...");
        probeChildFrames(step, _iframeEls_phase1).then((bestIframe) => {
          if (myToken !== renderRequestToken) return;
          if (!isGuideActive || !activeGuide || activeGuide.steps[currentStepIndex] !== step) return;

          if (bestIframe) {
//             console.log("[BusinessGuide-Review] selector探测: iframe中找到selector匹配\"" + step.selector + "\"，采用iframe结果");
            currentHighlightedElement = bestIframe.iframeEl;
            if (bestIframe.selector) {
              currentHighlightedElement.__appguide_review_iframe_selector = bestIframe.selector;
            }
            renderBubble(step, bestIframe.iframeEl);
          } else {
            // selector not found in any frame, fall through to Phase 1b (S0)
//             console.log("[BusinessGuide-Review] selector未在iframe中找到\"" + step.selector + "\"，降级到S0...");
            phase1_s0(step, myToken, retriesLeft, _iframeEls_phase1);
          }
        });
        return;
      }

      // selector misses main page, no iframes: fall through to S0
    }

    phase1_s0(step, myToken, retriesLeft, _iframeEls_phase1);
  }

  // Phase 1b: S0 cross-frame matching
  function phase1_s0(step, myToken, retriesLeft, _iframeEls) {
//     console.log("[BusinessGuide-Review] phase1_s0 进入, s0匹配\"" + step.title + "\", iframe数=" + (_iframeEls ? _iframeEls.length : 0));
    if (myToken !== renderRequestToken) return;
    const s0Main = findS0Match(step);

    // 1a. S0 hit on main page, no iframes
    if (s0Main && _iframeEls.length === 0) {
//       console.log("[BusinessGuide-Review] S0匹配\"" + step.title + "\"于主页面，无iframe，直接采用");
      usedElements.add(s0Main.element);
      currentHighlightedElement = s0Main.element;
      createHighlightForElement(s0Main.element, step.highlightStyle);
      renderBubble(step, s0Main.element);
      return;
    }

    // 1b. S0 hit on main page, with iframes: render now, probe iframes in background
    if (s0Main && _iframeEls.length > 0) {
//       console.log("[BusinessGuide-Review] S0匹配\"" + step.title + "\"于主页面，并行探测iframe的S0匹配...");
      usedElements.add(s0Main.element);
      currentHighlightedElement = s0Main.element;
      createHighlightForElement(s0Main.element, step.highlightStyle);
      renderBubble(step, s0Main.element);
      probeChildFramesForS0(step, _iframeEls).then((bestIframe) => {
        if (myToken !== renderRequestToken) return;
        if (!isGuideActive || !activeGuide || activeGuide.steps[currentStepIndex] !== step) return;
        if (bestIframe) {
//           console.log("[BusinessGuide-Review] S0探测: iframe也发现S0匹配\"" + step.title + "\"，主页面结果已使用（同分优先主页）");
        } else {
//           console.log("[BusinessGuide-Review] S0探测: iframe无S0匹配，主页面结果唯一");
        }
      });
      return;
    }

    // 1c. S0 missed on main page, but has iframes: probe iframes for S0 (async)
    if (!s0Main && _iframeEls.length > 0) {
//       console.log("[BusinessGuide-Review] S0未命中主页\"" + step.title + "\"，探测iframe的S0匹配...");
      probeChildFramesForS0(step, _iframeEls).then((bestIframe) => {
        if (myToken !== renderRequestToken) return;
        if (!isGuideActive || !activeGuide || activeGuide.steps[currentStepIndex] !== step) return;

        if (bestIframe) {
//           console.log("[BusinessGuide-Review] S0探测: iframe中发现S0匹配\"" + step.title + "\"，采用iframe结果");
          currentHighlightedElement = bestIframe.iframeEl;
          if (bestIframe.selector) {
            currentHighlightedElement.__appguide_review_iframe_selector = bestIframe.selector;
          }
          renderBubble(step, bestIframe.iframeEl);
        } else {
//           console.log("[BusinessGuide-Review] S0未在任何frame匹配\"" + step.title + "\"，降级到S1-S3...");
          resolveWithS1S3(step, myToken, retriesLeft);
        }
      });
      return;
    }

    // 1d. S0 missed on main page, no iframes: fall back to Phase 2
//     console.log("[BusinessGuide-Review] S0未命中\"" + step.title + "\"，无iframe，降级到S1-S3...");
    resolveWithS1S3(step, myToken, retriesLeft);
  }

  // Phase 2: S1-S3 local matching + retries + low-confidence iframe probing
  // (selector already handled in Phase 1a, so Phase 2 only does semantic S1-S3)
  function resolveWithS1S3(step, myToken, retriesLeft) {
    if (myToken !== renderRequestToken) return;
    resolveWithS1S3Local(step, myToken, retriesLeft);
  }

  function resolveWithS1S3Local(step, myToken, retriesLeft) {
    if (myToken !== renderRequestToken) return;
    const local = resolveLocalTarget(step);
    if (local) {
      const LOW_CONFIDENCE = 80;
      const _iframeEls = IS_TOP_FRAME ? Array.from(document.querySelectorAll("iframe")) : [];
      if (local.scorePercent < LOW_CONFIDENCE && _iframeEls.length > 0) {
//         console.log("[BusinessGuide-Review] 本地匹配到\"" + step.title + "\"，置信度仅" + local.scorePercent + "%，并行探测iframe以比较...");
        probeChildFrames(step, _iframeEls).then((bestIframe) => {
          if (myToken !== renderRequestToken) return;
          if (!isGuideActive || !activeGuide || activeGuide.steps[currentStepIndex] !== step) return;
          if (bestIframe && bestIframe.score > local.scorePercent) {
//             console.log("[BusinessGuide-Review] iframe匹配(" + bestIframe.score + "%)优于本地(" + local.scorePercent + "%)，采用iframe结果");
            currentHighlightedElement = bestIframe.iframeEl;
            if (bestIframe.selector) {
              currentHighlightedElement.__appguide_review_iframe_selector = bestIframe.selector;
            }
            renderBubble(step, bestIframe.iframeEl);
          } else {
//             console.log("[BusinessGuide-Review] 本地匹配(" + local.scorePercent + "%)优于或等于iframe，采用本地结果");
            usedElements.add(local.element);
            currentHighlightedElement = local.element;
            createHighlightForElement(local.element, step.highlightStyle);
            renderBubble(step, local.element);
          }
        });
        return;
      }
      usedElements.add(local.element);
      currentHighlightedElement = local.element;
      createHighlightForElement(local.element, step.highlightStyle);
      renderBubble(step, local.element);
      return;
    }

    if (retriesLeft > 0) {
//       console.log("[BusinessGuide-Review] 本文档内暂未找到\"" + step.title + "\"，" + LOCAL_RETRY_DELAY_MS + "ms后重试（剩余" + retriesLeft + "次）...");
      waitForDomSettleOrTimeout(LOCAL_RETRY_DELAY_MS).then(() => {
        resolveWithS1S3Local(step, myToken, retriesLeft - 1);
      });
      return;
    }

    const __iframeEls = IS_TOP_FRAME ? Array.from(document.querySelectorAll("iframe")) : [];
    if (__iframeEls.length === 0) {
      handleTargetNotFound(step);
      return;
    }

    probeChildFrames(step, __iframeEls).then((bestIframe) => {
      if (myToken !== renderRequestToken) return;
      if (!isGuideActive || !activeGuide || activeGuide.steps[currentStepIndex] !== step) return;
      if (bestIframe) {
        currentHighlightedElement = bestIframe.iframeEl;
        if (bestIframe.selector) {
          currentHighlightedElement.__appguide_review_iframe_selector = bestIframe.selector;
        }
        renderBubble(step, bestIframe.iframeEl);
      } else {
        handleTargetNotFound(step);
      }
    });
  }


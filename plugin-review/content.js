  /**
   * 判断 id 是否像框架自动生成的（应予忽略）
   * 匹配模式如：el-id-123-456、:r1:、data-v-xxx 这类 Vue/React 自动生成id
   */
  function isAutoGeneratedId(id) {
    if (!id) return true;
    // React / Vue 自动生成 id 模式
    if (/^el-id-\d+-\d+$/.test(id)) return true;
    // Emotion / styled-components
    if (/^:\w+:/.test(id)) return true;
    // 纯数字 id
    if (/^\d+$/.test(id)) return true;
    // 哈希类 id（如 css-xxxxx）
    if (/^[a-f0-9]{6,}$/.test(id) && id.length >= 8) return true;
    // data-v-xxxx（Vue scoped）
    if (/^data-v-/.test(id)) return true;
    // 极短随机字符串（<4字符）
    if (id.length <= 3 && /^[a-z0-9]+$/i.test(id)) return true;
    return false;
  }

  /**
   * 判断 class 是否像工具类/状态类（应予过滤）
   */
  function isUtilityClass(cls) {
    if (!cls) return true;
    // 纯数字、单字母
    if (/^\d+$/.test(cls) || /^[a-z]$/i.test(cls)) return true;
    // 状态标记类
    if (/^(is-|has-|was-|should-|can-|will-|active|disabled|enabled|open|close|show|hide|visible|hidden|selected|checked|focused|hover|error|success|warning|loading|empty|first|last|even|odd)/i.test(cls)) return true;
    // 尺寸/间距工具类（Tailwind-like）
    if (/^(p|m|w|h|t|b|l|r|x|y|top|bottom|left|right|flex|grid|block|inline|text|font|bg|border|rounded|shadow|opacity|z|overflow|cursor|pointer|relative|absolute|fixed|sticky|float|clear|align|justify|self|order|grow|shrink|basis|gap|space)-/.test(cls)) return true;
    // CSS module hash
    if (/^[_-][a-zA-Z0-9]{5,}$/.test(cls)) return true;
    // 含特殊字符（: [ ]）
    if (/[:\[\]]/.test(cls)) return true;
    return false;
  }

  /**
   * 生成稳定、唯一、可长期复用的 CSS selector 字符串
   * @param {Element} element - DOM 元素
   * @returns {string} 唯一的 CSS selector
   */
  function generateStableSelector(element) {
    if (!element || !element.tagName) return "";

    const tag = element.tagName.toLowerCase();
    const id = element.id || "";

    // 策略A：从 id 生成 selector（最优先）
    if (id && !isAutoGeneratedId(id)) {
      const sel = `#${CSS.escape(id)}`;
      try {
        if (document.querySelectorAll(sel).length === 1) {
          return sel;
        }
      } catch (e) { /* 非法选择器，回退 */ }
    }

    // 策略B：从 class 生成 selector
    let classList = [];
    if (typeof element.className === "string" && element.className.trim()) {
      classList = element.className.trim().split(/\s+/).filter(c => !isUtilityClass(c));
    }

    // 尝试用 tag + 可靠class 组合
    if (classList.length > 0) {
      // 优先试单个最可靠的class
      for (const cls of classList) {
        const sel = `${tag}.${CSS.escape(cls)}`;
        try {
          if (document.querySelectorAll(sel).length === 1) {
            return sel;
          }
        } catch (e) { /* 跳过 */ }
      }

      // 单个不行，试两个class组合（从前往后取）
      for (let i = 0; i < classList.length; i++) {
        for (let j = i + 1; j < classList.length; j++) {
          const sel = `${tag}.${CSS.escape(classList[i])}.${CSS.escape(classList[j])}`;
          try {
            if (document.querySelectorAll(sel).length === 1) {
              return sel;
            }
          } catch (e) { /* 跳过 */ }
        }
      }
    }

    // 策略C：结构定位兜底 —— 从最近的、有稳定标识的祖先开始，拼接 nth-of-type
    let path = [];
    let current = element;

    // 一直往上走到 body：每一层都先试当前累积路径，命中唯一就用最短的那条；
    // 走完全程时从 body 起的逐层精确链必然唯一，不再因为深度上限而放弃。
    for (let depth = 0; current && current !== document.body && current !== document.documentElement; depth++) {
      const curTag = current.tagName.toLowerCase();
      const curId = current.id || "";

      // 如果当前层级有可靠 id，从这里开始用 #id 锚定，不再往上
      if (curId && !isAutoGeneratedId(curId) && depth > 0) {
        const anchorSel = `#${CSS.escape(curId)}`;
        let anchored = false;
        try {
          if (document.querySelectorAll(anchorSel).length === 1) {
            path.unshift(anchorSel);
            anchored = true;
            const fullSel = path.join(" > ");
            if (document.querySelectorAll(fullSel).length === 1) {
              return fullSel;
            }
          }
        } catch (e) { /* 跳过 */ }
        if (anchored) path.shift();   // 锚点没能定唯一，撤销，继续按结构向上
      }

      // 计算当前元素在同级兄弟中的 nth-of-type
      const parent = current.parentElement;
      if (parent) {
        const siblings = Array.from(parent.children).filter(c => c.tagName === current.tagName);
        if (siblings.length > 1) {
          const idx = siblings.indexOf(current) + 1;
          path.unshift(`${curTag}:nth-of-type(${idx})`);
        } else {
          path.unshift(curTag);
        }
      } else {
        path.unshift(curTag);
      }

      // 检查当前路径是否已唯一
      const fullSel = path.join(" > ");
      try {
        if (document.querySelectorAll(fullSel).length === 1) {
          return fullSel;
        }
      } catch (e) { /* 跳过 */ }

      current = parent;
    }

    // 最终兜底：把整条 nth-of-type 路径挂到 body 下，必须唯一才返回。
    // 正常情况循环停在 body，path 首段就是 body 的直接子元素，用子代组合器；
    // 元素在 body 之外（head / 游离节点 / shadow DOM）时 current 是 html 或 null，
    // 用后代组合器，且必然匹配不到 —— 返回 "" 交给语义检索。
    const fullSel = (current === document.body ? "body > " : "body ") + path.join(" > ");
    try {
      if (document.querySelectorAll(fullSel).length === 1) {
        return fullSel;
      }
      // 不唯一，返回空字符串——调用方将退回语义匹配
      return "";
    } catch (e) {
      return "";
    }
  }

  // ARIA role → 控件类型 映射（词表参考 scanDOM 里的 INTERACTIVE_ROLES）
  const ROLE_CONTROL_TYPE = {
    button: "button",
    checkbox: "checkbox",
    radio: "radio",
    switch: "switch",
    combobox: "select",
    listbox: "select",
    option: "option",
    tab: "tab",
    menuitem: "menuitem",
    textbox: "input",
    slider: "input",
    spinbutton: "input",
    link: "a",
  };

  // 原生语义标签直接短路判定的集合（避免 div/span/svg/img 等容器标签
  // 在真正有意义的 role 之前被误判为"就是它自己"）
  const NATIVE_CONTROL_TAGS = {
    select: "select",
    textarea: "textarea",
    button: "button",
    a: "a",
    ul: "ul",
    ol: "ul",
    li: "li",
    option: "option",
    label: "label",
  };

  // 取值类控件：需要用户输入/选择一个值（按钮型 input 与 hidden 不算）
  const VALUE_CONTROL_SELECTOR = [
    "input:not([type='button']):not([type='submit']):not([type='reset']):not([type='image']):not([type='hidden'])",
    "textarea", "select", "[contenteditable='true']",
    "[role='textbox']", "[role='combobox']", "[role='listbox']", "[role='checkbox']", "[role='radio']",
    "[role='switch']", "[role='slider']", "[role='spinbutton']", "[role='option']",
  ].join(", ");

  // 框架取值组件的外层容器（内部 DOM 往往没有语义标签/role）
  const VALUE_WIDGET_SELECTOR = [
    ".el-input", ".el-textarea", ".el-select", ".el-select-v2", ".el-cascader", ".el-date-editor", ".el-input-number",
    ".el-checkbox", ".el-radio", ".el-switch", ".el-slider", ".el-select-dropdown__item", ".el-autocomplete",
    ".ant-input", ".ant-input-affix-wrapper", ".ant-select", ".ant-picker", ".ant-input-number",
    ".ant-checkbox-wrapper", ".ant-radio-wrapper", ".ant-switch", ".ant-select-item-option",
  ].join(", ");

  // 动作类元素：点击即执行，不承载取值
  const ACTION_SELECTOR =
    "button, a[href], [role='button'], [role='link'], input[type='button'], input[type='submit'], input[type='reset'], input[type='image']";

  // 文件上传：真实 file input 常被隐藏，审核时点到的多是触发按钮/拖拽区/label
  const FILE_INPUT_SELECTOR = "input[type='file']";
  // 上传组件的触发区容器（不含 .el-upload-list / .ant-upload-list 文件列表，那里的删除按钮不是上传）
  const UPLOAD_WIDGET_SELECTOR = ".el-upload, .ant-upload";

  // 下拉选择组件根（含多选/级联；自动完成输入框不算，见 AUTOCOMPLETE_SELECTOR）
  const SELECT_WIDGET_SELECTOR =
    ".el-select, .el-select-v2, .el-cascader, .ant-select:not(.ant-select-auto-complete), .ant-cascader";
  const AUTOCOMPLETE_SELECTOR = ".el-autocomplete, .ant-select-auto-complete";
  // 这些组件内部还嵌着 .el-input 等容器，归并控件单元时优先取它们
  const COMPOSITE_WIDGET_SELECTOR = SELECT_WIDGET_SELECTOR + ", " + AUTOCOMPLETE_SELECTOR;
  const COMBOBOX_SELECTOR = "[role='combobox'], [role='listbox'], [aria-haspopup='listbox']";
  // resolveValueControl 的特殊返回值：元素包裹了多个取值控件，是参数项但无法确定具体是哪一个
  const MULTIPLE_CONTROLS = {};

  /**
   * 判定当前定位元素是否为文件上传控件：file input 本身、关联它的 label、
   * Element Plus / antd 上传组件的触发区，或与隐藏 file input 同处一个小容器的自定义触发按钮。
   * @param {Element} element - DOM 元素
   * @returns {boolean}
   */
  function isFileUploadControl(element) {
    try {
      if (element.matches(FILE_INPUT_SELECTOR)) return true;
      const label = element.closest("label");
      if (label && label.control && label.control.matches(FILE_INPUT_SELECTOR)) return true;
      const widget = element.closest(UPLOAD_WIDGET_SELECTOR);
      if (widget && widget.querySelector(FILE_INPUT_SELECTOR)) return true;
      // 自定义上传：向上最多 3 层，取第一个含 file input 的容器；
      // 只有它仅含这一个取值控件、至多一个动作元素时才算（避免大表单里的提交按钮被误判）
      for (let el = element, depth = 0; el && el !== document.body && depth <= 3; el = el.parentElement, depth++) {
        if (!el.querySelector(FILE_INPUT_SELECTOR)) continue;
        return el.querySelectorAll(VALUE_CONTROL_SELECTOR).length === 1 &&
               el.querySelectorAll(ACTION_SELECTOR).length <= 1;
      }
    } catch (e) { /* 非法选择器等异常，按非上传处理 */ }
    return false;
  }

  /**
   * 识别当前操作元素的"控件类型"（input/select/radio/checkbox/button/a/ul 等）。
   * 很多框架（antd/Element Plus/MUI 等）渲染出来的真实标签/class 并不含这些语义关键词，
   * 审核时定位到的往往不是控件本身（父容器、组件内部图标/文字、label），因此先按
   * resolveValueControl（与 detectParameters 同一套解析）找到元素代表的取值控件再分类：
   *   0. 文件上传控件（含其触发按钮/拖拽区/label）→ fileupload
   *   1. 代表单个取值控件：下拉选择 → select；框架容器取其内部原生控件分类；否则分类控件本身
   *   2. 非取值控件 / 包裹多个取值控件 → 按元素自身分类（detectElementControlType）
   * @param {Element} element - DOM 元素
   * @returns {string} 控件类型
   */
  function detectControlType(element) {
    if (!element || !element.tagName) return "";
    if (isFileUploadControl(element)) return "fileupload";

    const unit = resolveValueControl(element);
    if (unit && unit !== MULTIPLE_CONTROLS) {
      if (isSelectControl(unit)) return "select";
      const inner = unit.matches(VALUE_WIDGET_SELECTOR) && unit.querySelector(VALUE_CONTROL_SELECTOR);
      return detectElementControlType(inner || unit);
    }
    return detectElementControlType(element);
  }

  /**
   * 按元素自身判定控件类型，命中即返回：
   *   1. 原生语义标签（input 再细分 type 属性）
   *   2. ARIA role（覆盖遵循无障碍规范但用 div 自定义渲染的框架组件）
   *   3. contenteditable（富文本编辑区）
   *   4. 通用可交互兜底（tabindex/onclick/cursor:pointer）
   *   5. 兜底：标签名本身
   * @param {Element} element - DOM 元素
   * @returns {string} 控件类型
   */
  function detectElementControlType(element) {
    const tag = element.tagName.toLowerCase();

    if (tag === "input") {
      const type = (element.getAttribute("type") || "text").toLowerCase();
      if (type === "checkbox") return "checkbox";
      if (type === "radio") return "radio";
      return "input";
    }
    if (NATIVE_CONTROL_TAGS[tag]) {
      return NATIVE_CONTROL_TAGS[tag];
    }

    const role = (element.getAttribute("role") || "").toLowerCase();
    if (role && ROLE_CONTROL_TYPE[role]) {
      return ROLE_CONTROL_TYPE[role];
    }

    if (element.isContentEditable) return "input";

    try {
      const hasTabindex = element.hasAttribute("tabindex") && element.getAttribute("tabindex") !== "-1";
      const hasOnclick = typeof element.onclick === "function" || element.hasAttribute("onclick");
      const cursorPointer = getComputedStyle(element).cursor === "pointer";
      if (hasTabindex || hasOnclick || cursorPointer) return "clickable";
    } catch (e) { /* 忽略 */ }

    return tag;
  }

  /**
   * 判定当前定位元素是否为"参数项"（取值类控件：各类 input/select/radio/checkbox/switch/下拉选项等）。
   * 审核时定位到的往往不是控件本身，而是其父容器、组件内部的图标/文字，甚至控件的 label，
   * 因此按以下顺序判定，命中即返回：
   *   0. 文件上传控件（含其触发按钮/拖拽区/label）→ true
   *   1. 动作类元素（按钮/链接）→ false
   *   2. 自身即取值控件或框架取值组件容器 → true
   *   3. 原生 <label> → 看其关联控件
   *   4. 位于取值组件内部（图标/文字等）→ true
   *   5. 包裹取值控件且不含动作元素的容器 → true
   *   6. 文本标签：同一表单项内有取值控件，或紧邻的兄弟节点是/包含取值控件 → true
   * @param {Element} element - DOM 元素
   * @returns {boolean}
   */
  function detectParameters(element) {
    if (!element || !element.tagName) return false;
    return isFileUploadControl(element) || !!resolveValueControl(element);
  }

  /**
   * 找出定位元素所代表的取值控件单元（detectParameters 的判定顺序，见其注释 1~6）。
   * @param {Element} element - DOM 元素
   * @returns {Element|object|null} 控件单元根；包裹多个控件时为 MULTIPLE_CONTROLS；非参数项为 null
   */
  function resolveValueControl(element) {
    if (!element || !element.tagName) return null;
    try {
      if (element.matches(ACTION_SELECTOR)) return null;

      if (element.matches(VALUE_CONTROL_SELECTOR) || element.isContentEditable ||
          element.matches(VALUE_WIDGET_SELECTOR)) {
        return unitRoot(element);
      }

      if (element.tagName === "LABEL" && element.control) {
        return element.control.matches(VALUE_CONTROL_SELECTOR) ? unitRoot(element.control) : null;
      }

      const inside = element.closest(VALUE_WIDGET_SELECTOR) || element.closest(VALUE_CONTROL_SELECTOR);
      if (inside) return unitRoot(inside);
      const parentLabel = element.closest("label");
      if (parentLabel && parentLabel.control && parentLabel.control.matches(VALUE_CONTROL_SELECTOR)) {
        return unitRoot(parentLabel.control);
      }

      const wrapsValueControl = (el) =>
        !!el.querySelector(VALUE_CONTROL_SELECTOR) && !el.querySelector(ACTION_SELECTOR);
      if (wrapsValueControl(element)) return wrappedUnit(element);

      if (looksLikeLabelText(element)) {
        const formItem = element.closest(".el-form-item, .ant-form-item");
        if (formItem) return wrappedUnit(formItem);
        const next = element.nextElementSibling;
        if (next && (next.matches(VALUE_CONTROL_SELECTOR) || next.matches(VALUE_WIDGET_SELECTOR))) return unitRoot(next);
        if (next && wrapsValueControl(next)) return wrappedUnit(next);
      }
    } catch (e) { /* 非法选择器等异常，按非参数项处理 */ }
    return null;
  }

  // 控件单元根：下拉/自动完成组件优先（内部嵌着 .el-input 等），其次框架取值组件容器
  function unitRoot(el) {
    return el.closest(COMPOSITE_WIDGET_SELECTOR) || el.closest(VALUE_WIDGET_SELECTOR) || el;
  }

  // 容器内全部取值控件/组件归并到单元根后：恰好一个则返回它，多个返回 MULTIPLE_CONTROLS，没有返回 null
  // （框架组件内部不一定有语义化控件，如非可搜索的 el-select，所以组件容器也要算上）
  function wrappedUnit(container) {
    const controls = container.querySelectorAll(VALUE_CONTROL_SELECTOR + ", " + VALUE_WIDGET_SELECTOR);
    const roots = new Set(Array.from(controls, unitRoot));
    if (roots.size === 0) return null;
    return roots.size === 1 ? roots.values().next().value : MULTIPLE_CONTROLS;
  }

  /**
   * 控件单元是否为下拉选择框：原生 select、Element/antd 下拉组件，或符合 ARIA 规范的
   * combobox/listbox（排除可自由输入的自动完成框）。
   * @param {Element} unit - resolveValueControl 返回的控件单元
   * @returns {boolean}
   */
  function isSelectControl(unit) {
    try {
      if (unit.tagName === "SELECT" || unit.matches(SELECT_WIDGET_SELECTOR)) return true;
      if (unit.closest(AUTOCOMPLETE_SELECTOR)) return false;
      const combo = unit.matches(COMBOBOX_SELECTOR) ? unit : unit.querySelector(COMBOBOX_SELECTOR);
      if (!combo) return false;
      if (combo.getAttribute("role") === "listbox") return true;
      const editable = combo.tagName === "INPUT" && !combo.readOnly &&
        /^(list|both|inline)$/.test(combo.getAttribute("aria-autocomplete") || "");
      return !editable;
    } catch (e) { return false; }
  }

  /**
   * 找出定位元素背后真正承载交互的元素（写入 domlocator）。定位元素可能是控件本身，
   * 也可能是其父容器、内部图标/文字或 label，按以下顺序判定，命中即返回：
   *   0. 文件上传控件 → 真实的 input[type=file]（常被隐藏）
   *   1. 取值控件单元：下拉 → combobox / 触发区；框架容器 → 内部原生控件；否则单元本身
   *   2. 自身或祖先是动作元素（按钮/链接）→ 该动作元素
   *   3. 容器内恰好一个动作元素 → 它
   *   4. 非标准实现：向上至多 5 层，找交互 role、tabindex、onclick，或 cursor:pointer 的起点
   *      （cursor 会继承，取自身为 pointer 而父元素不是的那一层）
   * 包裹多个取值控件或无任何交互迹象时返回 null，不硬猜。
   * @param {Element} element - DOM 元素
   * @returns {Element|null}
   */
  function resolveInteractiveElement(element) {
    if (!element || !element.tagName) return null;
    try {
      if (isFileUploadControl(element)) {
        if (element.matches(FILE_INPUT_SELECTOR)) return element;
        const label = element.closest("label");
        if (label && label.control && label.control.matches(FILE_INPUT_SELECTOR)) return label.control;
        const widget = element.closest(UPLOAD_WIDGET_SELECTOR);
        const inWidget = widget && widget.querySelector(FILE_INPUT_SELECTOR);
        if (inWidget) return inWidget;
        for (let el = element, depth = 0; el && el !== document.body && depth <= 3; el = el.parentElement, depth++) {
          const input = el.querySelector(FILE_INPUT_SELECTOR);
          if (input) return input;
        }
        return null;
      }

      const unit = resolveValueControl(element);
      if (unit === MULTIPLE_CONTROLS) return null;
      if (unit) {
        if (isSelectControl(unit)) {
          return (unit.matches(COMBOBOX_SELECTOR) ? unit : unit.querySelector(COMBOBOX_SELECTOR)) ||
                 unit.querySelector(SELECT_TRIGGER_SELECTOR) || unit;
        }
        if (unit.matches(VALUE_CONTROL_SELECTOR) || unit.isContentEditable) return unit;
        return unit.querySelector(VALUE_CONTROL_SELECTOR) || unit;
      }

      const action = element.closest(ACTION_SELECTOR);
      if (action) return action;
      const actions = element.querySelectorAll(ACTION_SELECTOR);
      if (actions.length === 1) return actions[0];

      for (let el = element, depth = 0; el && el !== document.body && depth <= 5; el = el.parentElement, depth++) {
        const role = (el.getAttribute("role") || "").toLowerCase();
        if (role && ROLE_CONTROL_TYPE[role]) return el;
        if (el.hasAttribute("tabindex") && el.getAttribute("tabindex") !== "-1") return el;
        if (typeof el.onclick === "function" || el.hasAttribute("onclick")) return el;
        const parent = el.parentElement;
        if (getComputedStyle(el).cursor === "pointer" &&
            (!parent || getComputedStyle(parent).cursor !== "pointer")) return el;
      }
    } catch (e) { /* 非法选择器等异常，按未识别处理 */ }
    return null;
  }


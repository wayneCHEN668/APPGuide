  /**
   * 从本地缓存的完整流程 JSON 中，按 pageIndex 构造 startGuideFromResolved 所需的数据格式
   * @param {Object} flowData - 完整流程 JSON（含 pages 数组）
   * @param {number} pageIndex - 当前要显示的页码（0-based）
   */
  function buildGuideFromLocalData(flowData, pageIndex) {
    if (!flowData || !flowData.pages || !Array.isArray(flowData.pages)) {
      console.error("[BusinessGuide-Review] 本地流程数据无效（缺少pages数组），请清除存储后重试",
        flowData ? Object.keys(flowData) : "null");
      return null;
    }
    const totalPages = flowData.pages.length;
    const targetPage = flowData.pages[pageIndex];
    if (!targetPage) {
      console.error(`[BusinessGuide-Review] 本地数据中找不到 pageIndex=${pageIndex} 的页面`);
      return null;
    }
    // 计算全局步骤偏移量和总步骤数
    let globalStepOffset = 0;
    let totalSteps = 0;
    for (let i = 0; i < totalPages; i++) {
      const steps = flowData.pages[i].steps;
      if (i < pageIndex) globalStepOffset += steps.length;
      totalSteps += steps.length;
    }
    // 给每步分配 globalStepNumber
    const steps = targetPage.steps.map((step, idx) => ({
      ...step,
      globalStepNumber: globalStepOffset + idx + 1,
    }));
    return {
      success: true,
      mode: "resume",
      flowId: flowData.id,
      flowTitle: flowData.title,
      pageIndex: pageIndex,
      totalPages: totalPages,
      globalStepOffset: globalStepOffset,
      totalSteps: totalSteps,
      page: { ...targetPage, steps },
    };
  }

  function getFlowStateIfValid() {
    return new Promise((resolve) => {
      try {
        chrome.storage.local.get([FLOW_STATE_KEY, FLOW_DATA_KEY], (result) => {
          if (chrome.runtime.lastError) { resolve(null); return; }
          const state = result[FLOW_STATE_KEY];
          if (!state) { resolve(null); return; }
          if (Date.now() - state.lastActiveAt > FLOW_TTL_MS) {
            try {
              chrome.storage.local.remove(FLOW_STATE_KEY);
              chrome.storage.local.remove(FLOW_DATA_KEY);
            } catch (e) { /* 静默 */ }
            resolve(null);
            return;
          }
          // 附加完整流程数据（如果已缓存）
          if (result[FLOW_DATA_KEY] && result[FLOW_DATA_KEY].flowData) {
            let fd = result[FLOW_DATA_KEY].flowData;
            // 兼容旧格式：如果存储的是 API 包裹层 { success, data: {...} }，自动解包
            if (fd && !fd.pages && fd.data && fd.data.pages) {
//               console.log("[BusinessGuide-Review] 检测到旧格式流程数据，自动解包");
              fd = fd.data;
            }
            state.flowData = fd;
          }
          resolve(state);
        });
      } catch (e) {
        console.warn("[BusinessGuide-Review] chrome.storage 不可用:", e.message);
        resolve(null);
      }
    });
  }


  /**
   * 将服务端 DB 扁平格式归一化为标准 pages 格式
   * DB 格式: { id, class, subclass, starturl, steps: [{ page:1, ... }, ...], updated_date }
   * 标准格式: { id, title, starturl, pages: [{ url, title, steps: [...] }, ...] }
   */
  function normalizeFlowData(raw) {
    if (!raw || !raw.steps) {
      console.warn("[BusinessGuide-Review] normalizeFlowData: 输入无效（缺少steps）");
      return null;
    }

    // 兼容三种 steps 格式：字符串 / 数组 / 对象
    let parsed = null;
    if (typeof raw.steps === "string") {
      try {
        parsed = JSON.parse(raw.steps);
      } catch (e) {
        console.warn("[BusinessGuide-Review] normalizeFlowData: steps JSON 解析失败", e);
        return null;
      }
    } else if (Array.isArray(raw.steps)) {
      parsed = { pages: raw.steps };
    } else if (raw.steps && typeof raw.steps === "object") {
      parsed = raw.steps;
    } else {
      console.warn("[BusinessGuide-Review] normalizeFlowData: steps 格式无法识别", typeof raw.steps);
      return null;
    }

    // 提取 pages 数组
    const pages = parsed.pages;
    if (!pages || !Array.isArray(pages)) {
      console.warn("[BusinessGuide-Review] normalizeFlowData: 解析后缺少pages数组");
      return null;
    }

    // 确保每页有 url 字段（回退到 starturl）
    pages.forEach(p => { if (!p.url) p.url = raw.starturl || ""; });

    const normalized = {
      id: raw.id,
      title: parsed.title || raw.class || raw.id || "",
      starturl: raw.starturl || "",
      pages: pages,
    };

//     console.log("[BusinessGuide-Review] normalizeFlowData: " + pages.length + "页, 总步骤 " +
//       pages.reduce((sum, p) => sum + (p.steps ? p.steps.length : 0), 0) + "步");
    return normalized;
  }


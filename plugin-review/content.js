  // S0-only iframe probe: sends "find-s0" message, waits for iframe workers
  // to run ONLY S0 matching. Separate from probeChildFrames (full pipeline).
  function probeChildFramesForS0(step, iframeEls, attemptsLeft) {
    if (attemptsLeft === undefined) attemptsLeft = IFRAME_PROBE_MAX_ATTEMPTS;

    return new Promise((resolve) => {
      const requestId = "s0_" + Date.now() + "_" + Math.random().toString(36).slice(2);
      let settled = false;
      let bestResult = null; // { iframeEl, score }

      const serializedStep = {
        title: step.title,
        description: step.description,
        selector: step.selector,
        tipPosition: step.tipPosition,
        highlightStyle: step.highlightStyle,
        clickText: step.clickText,
        actionType: step.actionType,
      };

      function onMessage(event) {
        const data = event.data;
        if (!data || data.__appguide_review !== true || data.type !== "find-s0-result") return;
        if (data.requestId !== requestId) return;
        if (!data.found) {
//           console.log("[BusinessGuide-Review] S0探测: 收到某个iframe的回复：没找到，继续等待...");
          return;
        }
        const matchedIframe = iframeEls.find((el) => el.contentWindow === event.source);
        if (!matchedIframe) {
          console.warn("[BusinessGuide-Review] S0探测: 收到found:true但反查不到对应<iframe>标签");
          return;
        }
        const score = typeof data.score === "number" ? data.score : 95;
//         console.log("[BusinessGuide-Review] S0探测: iframe回复找到目标，置信度: " + score + "%");
        if (!bestResult || score > bestResult.score) {
          bestResult = { iframeEl: matchedIframe, score };
        }
      }
      window.addEventListener("message", onMessage);

      let sentCount = 0;
      iframeEls.forEach((el, idx) => {
        try {
          if (!el.contentWindow) {
            console.warn("[BusinessGuide-Review] S0探测: 第" + (idx + 1) + "个<iframe>无contentWindow，跳过");
            return;
          }
          el.contentWindow.postMessage(
            { __appguide_review: true, type: "find-s0", requestId, step: serializedStep },
            "*"
          );
          sentCount++;
        } catch (e) {
          console.warn("[BusinessGuide-Review] S0探测: 向第" + (idx + 1) + "个<iframe>发送失败:", e);
        }
      });
//       console.log("[BusinessGuide-Review] S0探测: 已向 " + sentCount + "/" + iframeEls.length + " 个<iframe>广播\"" + step.title + "\"，requestId=" + requestId + "，第" + (IFRAME_PROBE_MAX_ATTEMPTS - attemptsLeft + 1) + "/" + IFRAME_PROBE_MAX_ATTEMPTS + "次尝试");

      setTimeout(() => {
        if (!settled) {
          settled = true;
          window.removeEventListener("message", onMessage);
          if (bestResult) {
//             console.log("[BusinessGuide-Review] S0探测结束，选取最佳iframe结果，置信度: " + bestResult.score + "%");
            resolve(bestResult);
          } else if (attemptsLeft > 1) {
            console.warn("[BusinessGuide-Review] S0探测超时，还有" + (attemptsLeft - 1) + "次重试机会，正在重试...");
            resolve(probeChildFramesForS0(step, iframeEls, attemptsLeft - 1));
          } else {
            console.warn("[BusinessGuide-Review] S0探测超时且重试次数已用完，requestId=" + requestId);
            resolve(null);
          }
        }
      }, IFRAME_PROBE_TIMEOUT_MS);
    });
  }



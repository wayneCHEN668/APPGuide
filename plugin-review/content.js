  // resolveLocalTarget —— 有 selector 就优先用，失败走语义匹配
  // ================================================================

  function resolveLocalTarget(step) {
    let targetElement = null;
    let matchMethod = "精确选择器定位";
    let scorePercent = 100;
    let strategy = null;

    // selector 匹配
    if (step.selector && step.selector !== "auto") {
      targetElement = document.querySelector(step.selector);
    }

    if (!targetElement) {
//       console.log(`[BusinessGuide-Review] 选择器 "${step.selector}" 缺失，正在启动本地语义匹配...`);
      const semanticMatch = findBestSemanticMatch(step);

      if (semanticMatch) {
        targetElement = semanticMatch.element;
        step.resolvedSelector = semanticMatch.selector;
        matchMethod = `语义模糊对齐 [${semanticMatch.label}]`;
        scorePercent = Math.round(semanticMatch.score * 100);
        strategy = semanticMatch.strategy || "unknown";

        // 升级隐藏/零尺寸 input 为可交互父容器
        if (targetElement && targetElement.tagName === 'INPUT') {
          const elSelect = targetElement.closest('.el-select');
          if (elSelect) {
            targetElement = elSelect;
            step.resolvedSelector = 'div.el-select';
          } else {
            const rect = targetElement.getBoundingClientRect();
            if (rect.width < 5 || rect.height < 5) {
              let parent = targetElement.parentElement;
              for (let i = 0; i < 4 && parent; i++) {
                const pr = parent.getBoundingClientRect();
                if (pr.width > 20 && pr.height > 20) {
                  targetElement = parent;
                  step.resolvedSelector = parent.className ?
                    `${parent.tagName.toLowerCase()}.${parent.className.split(/\s+/).filter(c => !c.includes(':') && c.length > 3).slice(0,2).join('.')}` :
                    parent.tagName.toLowerCase();
                  break;
                }
                parent = parent.parentElement;
              }
            }
          }
        }

        // 命中诊断日志 + 不可见兜底（审核版恢复）：定位假阳性/隐藏元素，避免静默失败
        try {
          const rect = targetElement.getBoundingClientRect();
          const cs = getComputedStyle(targetElement);
//          const x = Math.round(rect.left + window.scrollX);
//          const y = Math.round(rect.top + window.scrollY);
//          const w = Math.round(rect.width);
//          const h = Math.round(rect.height);
          const zeroSize = rect.width === 0 || rect.height === 0;
//          console.log(`[BusinessGuide-Review] 语义对齐成功！绑定到 "${semanticMatch.selector}"，置信度 ${scorePercent}%`);
//          console.log(`[BusinessGuide-Review] 匹配元素详情 —— 位置:(${x},${y}) 尺寸:${w}×${h} display:${cs.display} visibility:${cs.visibility} opacity:${cs.opacity}` + (zeroSize ? " ⚠️ 尺寸为0，可能是不可见元素" : ""), targetElement);

          // 拒绝零尺寸/隐藏的假阳性命中，改走重试→人工确认
          if (zeroSize || cs.display === 'none' || cs.visibility === 'hidden' || cs.opacity === '0') {
            console.warn("[BusinessGuide-Review] 命中零尺寸/隐藏元素，判为未找到，进入人工确认:", step.resolvedSelector, targetElement);
            targetElement = null;
            step.resolvedSelector = null;
          }
        } catch (e) {
          // 诊断信息获取失败不影响主流程
        }
      } else {
        step.resolvedSelector = null;
      }
    } else {
      step.resolvedSelector = step.selector;
    }

    if (!targetElement) return null;
    return { element: targetElement, matchMethod, scorePercent, strategy };
  }

